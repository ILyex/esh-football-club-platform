export async function ensureDefaultTestDefinitions(db: PrismaClient): Promise<void> {
  for (const def of DEFAULT_TEST_DEFINITIONS) {
    await db.testDefinition.upsert({
      where: { code: def.code },
      update: {
        name: def.name,
        category: def.category,
        description: def.description,
        primaryUnit: def.primaryUnit,
        secondaryUnit: def.secondaryUnit,
        direction: def.direction,
        calculationStrategy: def.calculationStrategy,
        defaultRetestDays: def.defaultRetestDays,
        instructions: def.instructions,
        active: def.active,
        version: def.version,
        displayOrder: def.displayOrder,
      },
      create: def,
    });
  }
}
